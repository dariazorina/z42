#include <stdlib.h>

int	ft_ultimate_range(int **range, int min, int max)
{
	if (max <= min)
	{
		*range = NULL;
		return (0);
	}
	*range = malloc(sizeof(int) * (max - min));
	if (*range == NULL)
		return (-1);
	while (max > min)
	{
		(*range)[max - min - 1] = max - 1;
		max--;
	}
	return (max - min);
}
