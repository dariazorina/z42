void	ft_rev_int_tab(int *tab, int size)
{
	int	r;
	int	i;

	i = 0;
	while (i < size / 2)
	{
		r = tab[i];
		tab[i] = tab[size - i - 1];
		tab[size - i - 1] = r;
		i++;
	}
}
